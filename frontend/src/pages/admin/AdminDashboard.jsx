export default function AdminDashboard() {
  const [stats, setStats] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  useEffect(() => {
    setLoading(true);
    getStats()
      .then(setStats)
      .catch((err) => setError(err?.response?.data?.detail || "Failed to load stats"))
      .finally(() => setLoading(false));
  }, []);

  return (
    <div>
      <h1 className="text-2xl font-bold text-white mb-1">Dashboard</h1>
      <p className="text-surface-500 text-sm mb-8">System overview and metrics</p>

      {loading && (
        <div className="flex items-center gap-3 justify-center py-16">
          <div className="spinner" />
          <span className="text-surface-400 text-sm">Loading stats…</span>
        </div>
      )}

      {error && (
        <div className="px-4 py-3 rounded-xl bg-red-500/10 border border-red-500/20 text-red-400 text-sm">
          {error}
        </div>
      )}

      {stats && (
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4 gap-4">
          {STAT_CONFIG.map((cfg) => (
            <StatCard
              key={cfg.key}
              title={cfg.title}
              value={stats[cfg.key]}
              icon={cfg.icon}
              color={cfg.color}
            />
          ))}
        </div>
      )}
    </div>
  );
}
